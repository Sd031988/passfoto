const dictionaries: Record<string, Record<TranslationKey, string>> = { de, en }

export type Language = keyof typeof dictionaries

/** Platzhalter, die in einem Text ersetzt werden können. */
export type TranslationVars = Record<string, string | number>

export function translate(language: Language, key: TranslationKey, vars?: TranslationVars): string {
  const dictionary = dictionaries[language] ?? de
  let value: string = dictionary[key] ?? de[key] ?? key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

export function formatNumber(value: number, language: Language, decimals = 1): string {
  return value.toLocaleString(language === 'en' ? 'en-US' : 'de-DE', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })
}

export function formatInteger(value: number, language: Language): string {
  return value.toLocaleString(language === 'en' ? 'en-US' : 'de-DE')
}

/**
 * Bindet Sprache und Platzhalter-Ersetzung an eine Komponente:
 * `const t = translator(language)` und danach `t('check.counts', { passed: 3 })`.
 */
export function translator(language: Language): (key: TranslationKey, vars?: TranslationVars) => string {
  return (key: TranslationKey, vars?: TranslationVars): string => translate(language, key, vars)
}